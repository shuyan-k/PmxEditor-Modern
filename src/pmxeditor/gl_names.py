def lookup(name: str, table: dict) -> str:
    key = name.strip()
    if key in table:
        return table[key]
    # 处理 .L/.R 后缀与全角空格
    key2 = key.replace(" ", "").replace("　", "")
    if key2 in table:
        return table[key2]
    return ""

def bone_zh(name: str) -> str:
    return lookup(name, _BONES)

def morph_zh(name: str) -> str:
    return lookup(name, _MORPHS)

_MAT_PREFIXES = (
    ("髪_", "头发"),
    ("衣装", "服装"),
    ("新規材質", "新建材质"),
)

def material_zh(name: str) -> str:
    zh = lookup(name, _MATERIALS)
    if zh:
        return zh
    key = name.strip()
    for prefix, base in _MAT_PREFIXES:
        if key.startswith(prefix):
            tail = key[len(prefix):].strip("_ ")
            if tail.isdigit():
                return "%s %s" % (base, tail)
            return base
    return ""

